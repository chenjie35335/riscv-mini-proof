#!/usr/bin/env python3
"""Generate dependency-aware builds for the existing auxiliary Coq foundation."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
roots = [ROOT / 'formal/flat-low', ROOT / 'formal/flat-low/staged-integration']
import json
report = json.loads((ROOT / 'formal/flat-low/final-snapshot-verification.json').read_text())
files = {Path(name).stem: ROOT / name for name in report['closure_sources']
         if name.startswith('formal/flat-low/')}
for source in files.values():
    if not source.is_file():
        raise SystemExit(f'Missing certified source: {source}')

def rel(path):
    return str(path.relative_to(ROOT))

def dependencies(source):
    result = []
    content = source.read_text()
    for group in re.findall(r'^Require (?:Import|Export) ([^.]+)\.', content, re.M):
        for name in group.split():
            if name in files:
                result.append(rel(files[name].with_suffix('.vo')))
            elif any((r / (name + '.v')).exists() for r in roots):
                raise SystemExit(f'{source.name}: local dependency missing from foundation: {name}')
    for namespace, group in re.findall(r'^From (firrtl|nbits|simplssrlib) Require (?:Import|Export) ([^.]+)\.', content, re.M):
        base = {'firrtl': 'firrtl2coq/src', 'nbits': 'firrtl2coq/lib/nbits', 'simplssrlib': 'firrtl2coq/lib/simplssrlib'}[namespace]
        for name in group.split():
            dep = ROOT / base / (name + '.v')
            if dep.exists():
                result.append(rel(dep.with_suffix('.vo')))
    return list(dict.fromkeys(result))

lines = [
    '# Generated by formal/generators/generate-proof-makefile.py; run make from the repository root.',
    '# Auxiliary proofs only: this is NOT the 45-assertion completion gate.',
    'COQC ?= /home/stormy/.opam/firrtl2coq/bin/coqc',
    "COQFLAGS := -Q firrtl2coq/lib/simplssrlib simplssrlib -Q firrtl2coq/lib/nbits nbits -R firrtl2coq/src firrtl -Q formal/flat-low '' -Q formal/flat-low/staged-integration ''",
    '.DELETE_ON_ERROR:',
    '.PHONY: all verify-artifacts',
    'all: verify-artifacts ' + ' '.join(rel(p.with_suffix('.vo')) for p in files.values()),
    'verify-artifacts:',
    '\t@sha256sum -c formal/flat-low/CoreSoc.before-proof.sha256',
    '\t@sha256sum -c formal/flat-low/legacy-CoreSoc.sha256',
]
for name, source in files.items():
    lines += [
        '',
        rel(source.with_suffix('.vo')) + ': ' + rel(source) + ' $(COQC) ' + ' '.join(dependencies(source)),
        f'\t@echo "Compiling {name}"',
        f'\t@$(COQC) $(COQFLAGS) {rel(source)} > formal/flat-low/{name}.incremental.log 2>&1 || {{ cat formal/flat-low/{name}.incremental.log; exit 1; }}',
    ]
output = ROOT / 'formal/flat-low/Makefile.proofs'
generated_path = output
generated_text = '\n'.join(lines) + '\n'
if not generated_path.exists() or generated_path.read_text() != generated_text:
    generated_path.write_text(generated_text)
print(f'Generated {rel(output)} for {len(files)} auxiliary proof units.')
